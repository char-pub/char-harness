/** Closed set of interface messages; no story text passes through this dictionary. */
export type MessageKey = keyof typeof en
/**
 * Read interface copy for one explicit language.
 * @param language - The selected interface language, independent from content locale.
 * @param key - A declared interface message.
 * @returns Localized interface text.
 */
export function translate(language: Language, key: MessageKey): string {
  return (language === 'zh' ? zh : en)[key]
}
